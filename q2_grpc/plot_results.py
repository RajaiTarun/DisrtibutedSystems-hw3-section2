"""
Makes the plots and summary tables for Q2 (gRPC streaming) from results/bench_results.csv

usage (from inside q2_grpc):   .venv/bin/python plot_results.py

output:
    plots/throughput_vs_workers.png   throughput vs number of workers, both strategies
    plots/query_latency_strategy.png  query latency vs number of workers, both strategies
    plots/throughput_vs_batch.png     throughput vs records per message
    plots/concurrent_queries.png      ingestion throughput and query latency vs number of dashboards
    plots/rate.png                    achieved vs requested stream rate
    results/summary.md                the numbers as markdown tables (for the report)
"""

import os
import pandas as pd
import matplotlib

matplotlib.use("Agg")  # no window, just write png files
import matplotlib.pyplot as plt

CSV = "results/bench_results.csv"
PLOTS = "plots"
SUMMARY = "results/summary.md"

# same validated palette and style as Q1
COLOR = {"interval": "#2a78d6", "roundrobin": "#eb6834"}
ONE = "#2a78d6"
SECOND = "#eb6834"
REFERENCE_GRAY = "#898781"
INK = "#0b0b0b"
INK_2 = "#52514e"
GRID = "#e1e0d9"
AXIS = "#c3c2b7"
SURFACE = "#fcfcfb"
NAME = {"interval": "By interval", "roundrobin": "Round-robin"}

plt.rcParams.update({
    "figure.facecolor": SURFACE,
    "axes.facecolor": SURFACE,
    "axes.edgecolor": AXIS,
    "axes.labelcolor": INK_2,
    "axes.titlecolor": INK,
    "axes.titlesize": 13,
    "axes.labelsize": 12,
    "xtick.labelsize": 11,
    "ytick.labelsize": 11,
    "legend.fontsize": 11,
    "axes.grid": True,
    "axes.axisbelow": True,
    "grid.color": GRID,
    "grid.linewidth": 0.8,
    "axes.spines.top": False,
    "axes.spines.right": False,
    "xtick.color": INK_2,
    "ytick.color": INK_2,
    "legend.frameon": False,
    "font.size": 11,
    "savefig.dpi": 150,
    "savefig.bbox": "tight",
})


def millions(x):
    return f"{x / 1e6:g}M"


def save(fig, name):
    path = os.path.join(PLOTS, name)
    fig.savefig(path)
    plt.close(fig)
    print("wrote", path)


def workers_axis(ax, values):
    ax.set_xscale("log", base=2)
    ax.set_xticks(values)
    ax.set_xticklabels([str(v) for v in values])
    ax.minorticks_off()


def fmt(x, pattern="{:.2f}"):
    return "-" if pd.isna(x) else pattern.format(x)


def main():
    os.makedirs(PLOTS, exist_ok=True)
    df = pd.read_csv(CSV)
    out = ["# Q2 benchmark summary", "", f"Generated by `plot_results.py` from `{CSV}`.", ""]

    # ---------------- workers + strategy ----------------
    wk = df[df["experiment"] == "workers"].sort_values("workers")
    if len(wk):
        n = int(wk["N"].iloc[0])
        ws = sorted(wk["workers"].unique())

        fig, ax = plt.subplots(figsize=(6.5, 3.8))
        for strat in ["interval", "roundrobin"]:
            r = wk[wk["strategy"] == strat]
            ax.plot(r["workers"], r["throughput"] / 1e6, color=COLOR[strat], linewidth=2, marker="o",
                    markersize=6, label=NAME[strat])
        workers_axis(ax, ws)
        ax.set_ylim(bottom=0)
        ax.set_xlabel("Number of workers")
        ax.set_ylabel("Million records / s")
        ax.set_title(f"Throughput vs workers (N = {millions(n)}, batch 1000)")
        ax.legend()
        save(fig, "throughput_vs_workers.png")

        fig, ax = plt.subplots(figsize=(6.5, 3.8))
        for strat in ["interval", "roundrobin"]:
            r = wk[wk["strategy"] == strat]
            ax.plot(r["workers"], r["q_p50_ms"], color=COLOR[strat], linewidth=2, marker="o",
                    markersize=6, label=NAME[strat])
        workers_axis(ax, ws)
        ax.set_yscale("log")
        ax.set_xlabel("Number of workers")
        ax.set_ylabel("Median query latency (ms, log scale)")
        ax.set_title("Query latency during the stream (1 dashboard, every 100 ms)")
        ax.legend()
        save(fig, "query_latency_strategy.png")

        out += [f"## Workers and distribution strategy (N = {millions(n)}, batch 1000, 1 dashboard every 100 ms)", "",
                "| Strategy | Workers | Throughput (rec/s) | Total (s) | Queries | Query p50 (ms) | Query p95 (ms) | Records per worker | Coord. mem (MB) | Coord. CPU (s) | Max worker mem (MB) | Workers CPU (s) | Correct |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for _, x in wk.sort_values(["strategy", "workers"]).iterrows():
            out.append(f"| {x.strategy} | {x.workers} | {x.throughput:,.0f} | {x.total_s:.2f} | {fmt(x.queries, '{:.0f}')} | "
                       f"{fmt(x.q_p50_ms)} | {fmt(x.q_p95_ms)} | {str(x.records_per_worker).replace(';', ', ')} | "
                       f"{fmt(x.coord_rss_mb, '{:.0f}')} | {fmt(x.coord_cpu_s)} | {fmt(x.worker_rss_mb_max, '{:.0f}')} | "
                       f"{fmt(x.worker_cpu_s_total)} | {x.correct} |")
        out.append("")

    # ---------------- batch size ----------------
    bt = df[df["experiment"] == "batch"].sort_values("batch")
    if len(bt):
        n = int(bt["N"].iloc[0])
        fig, ax = plt.subplots(figsize=(6.5, 3.8))
        ax.plot(bt["batch"], bt["throughput"], color=ONE, linewidth=2, marker="o", markersize=6)
        for _, x in bt.iterrows():
            ax.annotate(f"{x.throughput / 1e3:,.0f}K", (x.batch, x.throughput), textcoords="offset points",
                        xytext=(0, 8), ha="center", color=INK_2, fontsize=10)
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.set_xlabel("Records per gRPC message (log scale)")
        ax.set_ylabel("Records / s (log scale)")
        ax.set_title(f"Throughput vs batch size (N = {millions(n)}, 4 workers)")
        ax.set_ylim(top=bt["throughput"].max() * 3)
        save(fig, "throughput_vs_batch.png")

        out += [f"## Batch size (N = {millions(n)}, 4 workers, interval)", "",
                "| Records per message | Messages | Throughput (rec/s) | Total (s) | Correct |", "|---|---|---|---|---|"]
        for _, x in bt.iterrows():
            out.append(f"| {x.batch} | {int(-(-x.N // x.batch)):,} | {x.throughput:,.0f} | {x.total_s:.2f} | {x.correct} |")
        out.append("")

    # ---------------- concurrent queries ----------------
    qu = df[df["experiment"] == "queries"].sort_values("query_clients")
    if len(qu):
        n = int(qu["N"].iloc[0])
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 3.8))
        labels = [str(q) for q in qu["query_clients"]]
        rects = ax1.bar(labels, qu["throughput"] / 1e6, width=0.55, color=ONE, edgecolor=SURFACE, linewidth=1.5)
        ax1.bar_label(rects, fmt="%.2f", padding=2, color=INK_2, fontsize=10)
        ax1.set_xlabel("Dashboards querying non-stop")
        ax1.set_ylabel("Million records / s")
        ax1.set_title("Ingestion throughput")
        ax1.grid(axis="x", visible=False)
        withq = qu[qu["query_clients"] > 0]
        ax2.plot(withq["query_clients"].astype(str), withq["q_p50_ms"], color=ONE, linewidth=2, marker="o",
                 markersize=6, label="median")
        ax2.plot(withq["query_clients"].astype(str), withq["q_p95_ms"], color=SECOND, linewidth=2, marker="o",
                 markersize=6, label="95th percentile")
        ax2.set_ylim(bottom=0)
        ax2.set_xlabel("Dashboards querying non-stop")
        ax2.set_ylabel("Query latency (ms)")
        ax2.set_title("Query latency")
        ax2.legend()
        fig.suptitle(f"Concurrent queries during the stream (N = {millions(n)}, 4 workers)", y=1.03,
                     fontsize=14, color=INK)
        save(fig, "concurrent_queries.png")

        out += [f"## Concurrent queries (N = {millions(n)}, 4 workers, interval, batch 1000)", "",
                "| Dashboards | Throughput (rec/s) | Total (s) | Queries answered | Query p50 (ms) | Query p95 (ms) | Query max (ms) | Correct |",
                "|---|---|---|---|---|---|---|---|"]
        for _, x in qu.iterrows():
            out.append(f"| {x.query_clients} | {x.throughput:,.0f} | {x.total_s:.2f} | {fmt(x.queries, '{:.0f}')} | "
                       f"{fmt(x.q_p50_ms)} | {fmt(x.q_p95_ms)} | {fmt(x.q_max_ms)} | {x.correct} |")
        out.append("")

    # ---------------- stream rate ----------------
    rt = df[df["experiment"] == "rate"]
    if len(rt):
        n = int(rt["N"].iloc[0])
        fixed = rt[rt["rate"] > 0].sort_values("rate")
        mx = rt[rt["rate"] == 0]
        fig, ax = plt.subplots(figsize=(6.5, 3.8))
        ax.plot(fixed["rate"] / 1e6, fixed["rate"] / 1e6, color=REFERENCE_GRAY, linewidth=1.5, linestyle="--",
                label="requested")
        ax.plot(fixed["rate"] / 1e6, fixed["throughput"] / 1e6, color=ONE, linewidth=2, marker="o", markersize=6,
                label="achieved")
        if len(mx):
            ax.axhline(float(mx["throughput"].iloc[0]) / 1e6, color=SECOND, linewidth=1.5, linestyle=":",
                       label="maximum (no rate limit)")
        ax.set_xlabel("Requested rate (million records / s)")
        ax.set_ylabel("Achieved (million records / s)")
        ax.set_title(f"Does the system keep up? (N = {millions(n)}, 4 workers)")
        ax.set_ylim(bottom=0)
        ax.set_xlim(left=0)
        ax.legend()
        save(fig, "rate.png")

        out += [f"## Stream rate (N = {millions(n)}, 4 workers, interval, batch 1000)", "",
                "| Requested (rec/s) | Achieved (rec/s) | Total (s) | Correct |", "|---|---|---|---|"]
        for _, x in rt.sort_values("rate").iterrows():
            req = "max" if x.rate == 0 else f"{x.rate:,.0f}"
            out.append(f"| {req} | {x.throughput:,.0f} | {x.total_s:.2f} | {x.correct} |")
        out.append("")

    out += ["## Correctness of every run (vs HW2 sequential)", "", "| Result | Runs |", "|---|---|"]
    for result, count in df["correct"].value_counts().items():
        out.append(f"| {result} | {count} |")
    out.append("")

    with open(SUMMARY, "w") as f:
        f.write("\n".join(out))
    print("wrote", SUMMARY)


if __name__ == "__main__":
    main()
